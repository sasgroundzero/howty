/** Rewrites src/data/games/more/index.ts from the game files in that folder. Run: node scripts/gen-index.mjs */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const dir = resolve(import.meta.dirname, '../src/data/games/more')
const found = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .flatMap((f) => [...readFileSync(resolve(dir, f), 'utf8').matchAll(/^export const (\w+) = tabletop\(\s*'[^']+',\s*(['"])(.+?)\2/gm)].map((m) => ({ file: f.slice(0, -3), name: m[1], title: m[3] })))
  .sort((a, b) => a.title.replace(/^The /, '').localeCompare(b.title.replace(/^The /, '')))
writeFileSync(
  resolve(dir, 'index.ts'),
  `/** Generated by scripts/gen-index.mjs: do not edit by hand. */\nimport type { GameDef } from '../../../engine/types'\n${found.map((g) => `import { ${g.name} } from './${g.file}'`).join('\n')}\n\nexport const MORE: GameDef[] = [\n${found.map((g) => `  ${g.name},`).join('\n')}\n]\n`,
)
console.log(`${found.length} games indexed`)
