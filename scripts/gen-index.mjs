/** Rewrites src/data/games/more/index.ts from the game files in that folder. Run: node scripts/gen-index.mjs */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const dir = resolve(import.meta.dirname, '../src/data/games/more')
const found = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .flatMap((f) => {
    const src = readFileSync(resolve(dir, f), 'utf8')
    // a game that imports the playing-card helpers is a standard-deck card game
    const cards = /from '\.\.\/playing'/.test(src)
    return [...src.matchAll(/^export const (\w+) = tabletop\(\s*'([^']+)',\s*(['"])(.+?)\3/gm)].map((m) => ({ file: f.slice(0, -3), name: m[1], id: m[2], title: m[4], cards }))
  })
  .sort((a, b) => a.title.replace(/^The /, '').localeCompare(b.title.replace(/^The /, '')))
writeFileSync(
  resolve(dir, 'index.ts'),
  `/** Generated by scripts/gen-index.mjs: do not edit by hand. */\nimport type { GameDef } from '../../../engine/types'\n${found.map((g) => `import { ${g.name} } from './${g.file}'`).join('\n')}\n\nexport const MORE: GameDef[] = [\n${found.map((g) => `  ${g.name},`).join('\n')}\n]\n\n/** Games played with ordinary playing cards (they import ../playing). */\nexport const CARD_IDS = new Set<string>([${found.filter((g) => g.cards).map((g) => `'${g.id}'`).join(', ')}])\n`,
)
console.log(`${found.length} games indexed`)
