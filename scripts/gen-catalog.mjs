/**
 * Writes src/data/games/catalog.ts: every built-in game's facts (small, loaded up front) and a loader per
 * game, so each game's 3D setup is its own file that the browser fetches only when that game is opened.
 * Also precomputes the card-game list and the daily-puzzle pool. Runs as part of `npm run index` and the build.
 */
import { build } from 'esbuild'
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '..')
const dir = resolve(root, 'src/data/games')
const skip = new Set(['index.ts', 'catalog.ts', 'compose.ts', 'kit.ts', 'layouts.ts', 'shared.ts', 'playing.ts', 'tags.ts', 'verified.ts', 'catanBoard.ts'])
const files = [
  ...readdirSync(dir).filter((f) => f.endsWith('.ts') && !skip.has(f)).map((f) => resolve(dir, f)),
  ...readdirSync(resolve(dir, 'more')).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => resolve(dir, 'more', f)),
]
const tmp = resolve(root, 'node_modules/.cache')
const entry = resolve(tmp, 'catalog-entry.ts')
const out = resolve(tmp, 'catalog-entry.mjs')
writeFileSync(entry, files.map((f, i) => `export * as m${i} from ${JSON.stringify(f)}`).join('\n'))
await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'warning' })
const mods = await import(pathToFileURL(out).href)
rmSync(entry)
rmSync(out)

const games = []
files.forEach((f, i) => {
  for (const [name, v] of Object.entries(mods[`m${i}`])) {
    if (v && typeof v === 'object' && typeof v.build === 'function' && v.meta) {
      const src = readFileSync(f, 'utf8')
      games.push({ def: v, name, path: './' + relative(dir, f).replace(/\.ts$/, ''), cards: /from '\.\.\/playing'/.test(src) })
    }
  }
})
// keep the library order of src/data/games/index.ts (it decides the home page's default demo, among other things)
const out2 = resolve(tmp, 'catalog-index.mjs')
await build({ entryPoints: [resolve(dir, 'index.ts')], bundle: true, platform: 'node', format: 'esm', outfile: out2, logLevel: 'warning' })
const { GAMES } = await import(pathToFileURL(out2).href)
rmSync(out2)
const rank = new Map(GAMES.map((g, i) => [g.id, i]))
games.sort((a, b) => (rank.get(a.def.id) ?? 1e9) - (rank.get(b.def.id) ?? 1e9))
if (games.length !== GAMES.length) throw new Error(`catalog found ${games.length} games but index.ts has ${GAMES.length}`)

/** Games whose finished table spells out their own name: too easy for the daily puzzle. Card tables all look alike. */
const fair = (g, cards) => {
  if (cards) return false
  const drawn = JSON.stringify(g.build(g.meta.defaultPlayers).pieces.map((p) => p.props)).toLowerCase()
  return !g.meta.title.toLowerCase().split(/[^a-z0-9]+/).some((w) => w.length > 3 && !['game', 'card', 'board', 'the'].includes(w) && [w, w.replace(/ies$/, 'y'), w.replace(/s$/, '')].some((v) => v.length > 3 && drawn.includes(v)))
}
const q = JSON.stringify
writeFileSync(
  resolve(dir, 'catalog.ts'),
  `/** Generated by scripts/gen-catalog.mjs: do not edit by hand. Run \`npm run index\` after adding a game. */
import type { GameDef, GameInfo } from '../../engine/types'

/** Every built-in game's facts, in library order. Small enough to load up front. */
export const CATALOG: GameInfo[] = [
${games.map(({ def }) => `  { id: ${q(def.id)}, meta: ${q(def.meta)} },`).join('\n')}
]

/** Loads one game's full 3D setup. Each is a separate file, fetched on first use. */
export const LOAD: Record<string, () => Promise<GameDef>> = {
${games.map(({ def, name, path }) => `  ${q(def.id)}: () => import(${q(path)}).then((m) => m.${name}),`).join('\n')}
}

/** Games played with ordinary playing cards. */
export const CARD_IDS = new Set<string>(${q(games.filter((g) => g.cards).map((g) => g.def.id))})

/** Games fair for the daily puzzle: their table does not spell out their name. */
export const DAILY_IDS = new Set<string>(${q(games.filter((g) => fair(g.def, g.cards)).map((g) => g.def.id))})
`,
)
console.log(`catalog: ${games.length} games, ${games.filter((g) => g.cards).length} card games, ${games.filter((g) => fair(g.def, g.cards)).length} in the daily pool`)
